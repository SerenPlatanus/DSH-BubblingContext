import { mkdir, readFile, writeFile } from 'node:fs/promises';
// DSH loads client bundles as lazy CommonJS factories. Only React is required;
// it is supplied by the host, so no dependency installation is needed.
const model = await readFile(new URL('../src/trajectory.cjs', import.meta.url), 'utf8');
const branch = await readFile(new URL('../src/branches.cjs', import.meta.url), 'utf8');
const graphState = await readFile(new URL('../src/graph-state.cjs', import.meta.url), 'utf8');
const contextSource = await readFile(new URL('../src/context-source.cjs', import.meta.url), 'utf8');
const renderWindow = await readFile(new URL('../src/render-window.cjs', import.meta.url), 'utf8');
let source = await readFile(new URL('../src/client.cjs', import.meta.url), 'utf8');
for(const [name,code] of Object.entries({trajectory:model,branches:branch,'graph-state':graphState,'context-source':contextSource,'render-window':renderWindow})){
  const needle=`require('./${name}.cjs')`;
  if(source.split(needle).length!==2)throw new Error(`Expected exactly one import: ${needle}`);
  source=source.replace(needle,()=>`(() => { const module = { exports: {} };\n${code}\nreturn module.exports; })()`);
}
if(/require\(['"]\.\//.test(source))throw new Error('Unbundled local dependency');
const output = new URL('../lib/', import.meta.url);
await mkdir(output, { recursive: true });
await writeFile(new URL('client.js', output),
  `// Generated by npm run build. Edit src/client.cjs instead.\nwindow.__ModuleLoader__.load({\n  id: "dsh-bubbling-context",\n  factory: (require) => {\n    const module = { exports: {} };\n    const exports = module.exports;\n${source}\n    return module.exports;\n  }\n});\n`);
console.log('Built lib/client.js');
